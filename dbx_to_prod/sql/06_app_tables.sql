-- Flask app logging table
-- Generated from the trial workspace DDL (structure only, no data).
-- Run in order in the prod workspace with a serverless SQL warehouse.

-- workspace.default.flask_app_logs (includes inference_ms, citations_ms and stage_timings_json)
CREATE TABLE IF NOT EXISTS workspace.default.flask_app_logs (
  user_id STRING COMMENT 'Internal corporate user identifier',
  session_id STRING COMMENT 'Application session identifier',
  app_version STRING COMMENT 'Deployed Flask application version',
  latency_ms BIGINT COMMENT 'End-to-end latency in milliseconds',
  event_id STRING NOT NULL COMMENT 'Unique identifier for the logged event',
  event_timestamp TIMESTAMP NOT NULL COMMENT 'UTC timestamp when the event occurred',
  question STRING COMMENT 'Question submitted by the user',
  answer STRING COMMENT 'Answer returned by the application',
  sources_json STRING COMMENT 'JSON array or object containing source metadata',
  source_count INT COMMENT 'Number of sources represented in sources_json',
  status STRING NOT NULL COMMENT 'Event outcome: success, error, or timeout',
  error_message STRING COMMENT 'Failure details when status is error or timeout',
  ingested_at TIMESTAMP NOT NULL COMMENT 'Timestamp when the row was written to Databricks',
  input_tokens BIGINT COMMENT 'Tokens submitted to the supervisor',
  output_tokens BIGINT COMMENT 'Tokens generated by the supervisor',
  total_tokens BIGINT COMMENT 'Total tokens consumed',
  agents_used_json STRING,
  inference_ms BIGINT COMMENT 'Supervisor/fast-path model time for the request',
  citations_ms BIGINT COMMENT 'Citation validation time after the model answered',
  stage_timings_json STRING COMMENT 'Per-stage milliseconds, e.g. {"coaching360":3,"tool":4400,"result":26400,"text":29600,"prepared":32200}')
USING delta
COMMENT 'Application event and question-answer logs for the corporate Flask application';

